package auth

import (
	"testing"
	"time"

	"github.com/pquerna/otp"
	"github.com/pquerna/otp/totp"
)

// currentCode generates a TOTP code for secret at timeNow().
func currentCode(secret string) (string, error) {
	return currentCodeAt(secret, timeNow())
}

// currentCodeAt generates a code at an explicit time.
func currentCodeAt(secret string, at time.Time) (string, error) {
	return totp.GenerateCodeCustom(secret, at, totp.ValidateOpts{
		Period:    totpPeriod,
		Skew:      0,
		Digits:    otp.DigitsSix,
		Algorithm: otp.AlgorithmSHA1,
	})
}

// pinTOTPClock freezes the package clock (clock.go) at at for the rest of the
// test, so a code generated by the test body and the window
// ValidateTOTPSecretStep applies are both read from the SAME instant.
//
// Without it a test that derives a code from timeNow() and then validates it
// reads the wall clock TWICE, and a 30s period boundary falling between the two
// reads moves the validator's base one step relative to the code — which is how
// TestIssue528StepToleranceUnchanged came to report "code from step +2 was
// accepted; the drift window widened" on a contended host (card t_6bf6c940).
// Swapping this package var is the established seam in this package
// (verifytoken_test.go:82, connecttoken_test.go:56, auth_test.go:45) and there is
// no t.Parallel() in it, so the swap is safe.
func pinTOTPClock(t *testing.T, at time.Time) {
	t.Helper()
	old := timeNow
	timeNow = func() time.Time { return at }
	t.Cleanup(func() { timeNow = old })
}

