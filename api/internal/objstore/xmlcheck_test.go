package objstore

// t_20af3915: the well-formedness bar a browser's XML parser applies to an
// `image/svg+xml` document, measured rather than assumed.
//
// The fixture is the prod bytes from the card: a `/* ... */` banner, then the
// root. encoding/xml decodes it WITHOUT an error (it returns the banner as
// character data), which is why a bare decoder drain would have shipped the bug
// again — so the negative case below is the assertion that keeps this honest.

import (
	"bytes"
	"encoding/xml"
	"errors"
	"io"
	"testing"
)

// prodBannerSVG is the exact body measured on prod v1.21.233 (card t_20af3915).
const prodBannerSVG = "/* Acme logo banner */\n" +
	`<svg xmlns="http://www.w3.org/2000/svg" width="10" height="10"><rect width="10" height="10"/></svg>` + "\n"

func TestValidateXMLDocumentAcceptsRenderableShapes(t *testing.T) {
	cases := map[string]string{
		"plain": `<svg xmlns="http://www.w3.org/2000/svg"><rect/></svg>`,
		"xml-comment": "<!-- generated by Acme -->\n" +
			`<svg xmlns="http://www.w3.org/2000/svg"><rect/></svg>`,
		"xml-prolog": "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n" +
			`<svg xmlns="http://www.w3.org/2000/svg"><rect/></svg>`,
		"prolog-and-comment": "<?xml version=\"1.0\"?><!-- c --><svg xmlns=\"http://www.w3.org/2000/svg\"/>",
		"doctype-external": "<?xml version=\"1.0\"?>\n" +
			`<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">` + "\n" +
			`<svg xmlns="http://www.w3.org/2000/svg"><rect/></svg>`,
		"utf8-bom":            "\ufeff" + `<svg xmlns="http://www.w3.org/2000/svg"><rect/></svg>`,
		"nested-with-text":    `<svg xmlns="http://www.w3.org/2000/svg"><title>Acme &amp; Co</title><rect/></svg>`,
		"trailing-whitespace": `<svg xmlns="http://www.w3.org/2000/svg"/>` + "\n\n  ",
		"trailing-comment":    `<svg xmlns="http://www.w3.org/2000/svg"/><!-- end -->`,
	}
	for name, body := range cases {
		t.Run(name, func(t *testing.T) {
			if err := ValidateXMLDocument([]byte(body)); err != nil {
				t.Fatalf("ValidateXMLDocument(%q) = %v, want nil (a browser renders this)", body, err)
			}
			// The control must also survive the decoder the card names, so the
			// "parses with xml.Decoder to zero error" half is measured here too.
			if err := drainXML([]byte(body)); err != nil {
				t.Fatalf("xml.Decoder rejected the control %q: %v", body, err)
			}
		})
	}
}

func TestValidateXMLDocumentRejectsBodiesABrowserCannotRender(t *testing.T) {
	cases := map[string]struct {
		body string
		want error
	}{
		// The card's own fixture. This is the one a decoder drain accepts.
		"block-comment-banner": {prodBannerSVG, ErrTextBeforeRoot},
		"hash-banner":          {"# Acme logo\n<svg xmlns=\"http://www.w3.org/2000/svg\"/>", ErrTextBeforeRoot},
		"text-after-root":      {`<svg/><!-- ok -->trailing`, ErrTextAfterRoot},
		"two-roots":            {`<svg/><svg/>`, ErrMultipleRoots},
		"no-root":              {"<!-- only a comment -->\n", ErrNoRootElement},
		"empty":                {"", ErrNoRootElement},
		"declaration-inside":   {`<svg><?xml version="1.0"?></svg>`, ErrDeclarationNotTop},
		"doctype-after-root":   {`<svg/><!DOCTYPE svg>`, ErrDirectiveAfterRoot},
	}
	for name, c := range cases {
		t.Run(name, func(t *testing.T) {
			err := ValidateXMLDocument([]byte(c.body))
			if !errors.Is(err, c.want) {
				t.Fatalf("ValidateXMLDocument(%q) = %v, want %v", c.body, err, c.want)
			}
		})
	}
}

// TestDecoderAloneAcceptsTheBannerSVG pins WHY the structural check exists: if a
// future simplification replaces ValidateXMLDocument with a bare decoder drain,
// this test documents that the defect returns (the drain below passes) and the
// negative case above starts failing. It is the bite-proof in test form.
func TestDecoderAloneAcceptsTheBannerSVG(t *testing.T) {
	if err := drainXML([]byte(prodBannerSVG)); err != nil {
		t.Fatalf("encoding/xml now rejects text before the root (%v) — the structural "+
			"check may be redundant; re-measure before trusting either assertion", err)
	}
	if err := ValidateXMLDocument([]byte(prodBannerSVG)); err == nil {
		t.Fatal("ValidateXMLDocument accepted the banner SVG; the browser shows a parsererror for it")
	}
}

// drainXML is the "decoder drain to EOF" the card prescribes, on its own.
func drainXML(body []byte) error {
	dec := xml.NewDecoder(bytes.NewReader(body))
	for {
		if _, err := dec.Token(); err != nil {
			if err == io.EOF {
				return nil
			}
			return err
		}
	}
}
