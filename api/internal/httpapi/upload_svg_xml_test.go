package httpapi

// t_20af3915: end-to-end through the handlers the dashboard's /media picker
// calls. An SVG is served as `image/svg+xml` with `X-Content-Type-Options:
// nosniff`, so the browser parses it as XML. A body whose first line is a
// `/* ... */` banner has TEXT BEFORE THE ROOT ELEMENT, which is a fatal XML
// parse error: the asset stored, listed, served 200 and then showed a
// `parsererror` instead of the merchant's logo (measured on prod v1.21.233).
//
// The card's two halves are pinned here, on BOTH upload endpoints:
//   - the exact measured body is refused 400 with the upload.svgInvalid code
//     (so the dashboard can render its own sentence instead of "Upload failed"),
//     and nothing is stored;
//   - the XML-legal `<!-- ... -->` control still uploads 200, is stored as
//     `.svg` / `image/svg+xml`, and the SERVED body parses with xml.Decoder to
//     zero error — the property the old tests never checked.
//
// Integration test: needs real Postgres (JOMFORM_TEST_DATABASE_URL), skipped
// when unset. Uses a fake object store so no live S3/MinIO is needed.

import (
	"bytes"
	"context"
	"encoding/json"
	"encoding/xml"
	"io"
	"net/http"
	"strings"
	"testing"
)

// prodBannerSVGBody is the exact upload measured on prod v1.21.233 through the
// /media file picker (card t_20af3915).
const prodBannerSVGBody = "/* Acme logo banner */\n" +
	`<svg xmlns="http://www.w3.org/2000/svg" width="10" height="10"><rect width="10" height="10"/></svg>` + "\n"

// xmlCommentSVGBody is the CONTROL measured on the same release and serve path:
// a leading XML comment is legal, and the browser rendered it (one <svg>, one
// <rect>, no parsererror).
const xmlCommentSVGBody = "<!-- generated by Acme -->\n" +
	`<svg xmlns="http://www.w3.org/2000/svg" width="10" height="10"><rect width="10" height="10"/></svg>` + "\n"

func TestSVGUploadRefusesANonWellFormedDocument(t *testing.T) {
	ctx := context.Background()
	h, accountID, raw, host := cssCommentUploadFixture(t)
	pool := bundleTestPool(t)

	storedSVGRows := func(t *testing.T) int {
		t.Helper()
		var n int
		if err := pool.QueryRow(ctx,
			`SELECT count(*) FROM media WHERE account_id = $1 AND "key" LIKE '%.svg'`, accountID).Scan(&n); err != nil {
			t.Fatalf("count media rows: %v", err)
		}
		return n
	}

	endpoints := []struct{ name, path string }{
		{"uploads-image", "/v1/rest/uploads/image"},
		{"uploads-asset", "/v1/rest/uploads/asset"},
	}
	for _, ep := range endpoints {
		// The refusal. The 400 has to carry BOTH the actionable prose (for
		// API-key/MCP callers, which never see the dashboard dictionary) and the
		// machine code (#6177) that resolves it to a localized sentence.
		t.Run(ep.name+"-rejects-block-comment-banner", func(t *testing.T) {
			before := storedSVGRows(t)
			code, body := signatureUpload(t, h, raw, ep.path, "logo.svg", "image/svg+xml", []byte(prodBannerSVGBody))
			if code != http.StatusBadRequest {
				t.Fatalf("banner-led SVG upload = %d, want 400 (body %s)", code, body)
			}
			var eb struct {
				Error string `json:"error"`
				Code  string `json:"code"`
			}
			if err := json.Unmarshal([]byte(body), &eb); err != nil {
				t.Fatalf("decode error body %q: %v", body, err)
			}
			if eb.Code != CodeUploadSVGInvalid {
				t.Fatalf("error code = %q, want %q (the dashboard maps the code, never the prose)", eb.Code, CodeUploadSVGInvalid)
			}
			if !strings.Contains(eb.Error, "not valid XML") || !strings.Contains(eb.Error, "before the root element") {
				t.Fatalf("error prose = %q, want a message naming the XML problem", eb.Error)
			}
			if after := storedSVGRows(t); after != before {
				t.Fatalf("media rows with a .svg key went %d → %d: the refused upload was stored anyway", before, after)
			}
		})

		// The control: an XML-legal document must still upload, and the bytes the
		// route SERVES must parse — the assertion the shipped tests lacked.
		t.Run(ep.name+"-accepts-xml-comment-svg", func(t *testing.T) {
			code, respBody := signatureUpload(t, h, raw, ep.path, "logo.svg", "image/svg+xml", []byte(xmlCommentSVGBody))
			if code != http.StatusOK {
				t.Fatalf("XML-comment SVG upload = %d, want 200 (body %s)", code, respBody)
			}
			var resp struct {
				URL string `json:"url"`
			}
			if err := json.Unmarshal([]byte(respBody), &resp); err != nil {
				t.Fatalf("decode upload response %q: %v", respBody, err)
			}
			mediaURLBase := "https://" + host + "/media/"
			key := strings.TrimPrefix(resp.URL, mediaURLBase)
			if key == resp.URL || key == "" {
				t.Fatalf("unexpected public url %q (want the workspace host %q prefix)", resp.URL, mediaURLBase)
			}
			if !strings.HasSuffix(key, ".svg") {
				t.Fatalf("XML-comment SVG stored under %q, want a .svg key", key)
			}
			stored, storedCT, err := h.Store.GetObject(ctx, key)
			if err != nil {
				t.Fatalf("GetObject(%q): %v", key, err)
			}
			if storedCT != "image/svg+xml" {
				t.Fatalf("stored content-type = %q, want image/svg+xml", storedCT)
			}
			if !bytes.Equal(stored, []byte(xmlCommentSVGBody)) {
				t.Fatalf("stored bytes differ from the upload (%d vs %d bytes)", len(stored), len(xmlCommentSVGBody))
			}
			m, err := h.Media.ByKey(ctx, accountID, key)
			if err != nil || m == nil {
				t.Fatalf("media row ByKey(%q): %v (row %v)", key, err, m)
			}
			if m.Mime != "image/svg+xml" {
				t.Fatalf("media.mime = %q, want image/svg+xml", m.Mime)
			}

			// A fresh code asset stays unserved until the scanner clears it
			// (issue #364) — a different question from its bytes.
			if err := h.Media.SetScanStatus(ctx, accountID, m.ID, "ok", ""); err != nil {
				t.Fatalf("mark media row scanned: %v", err)
			}
			rec := restMediaServe(t, h, host, key)
			if rec.Code != http.StatusOK {
				t.Fatalf("GET /media/%s on %s = %d (%s), want 200", key, host, rec.Code, rec.Body.String())
			}
			if got := rec.Header().Get("Content-Type"); got != "image/svg+xml" {
				t.Fatalf("served content-type = %q, want image/svg+xml", got)
			}
			if got := rec.Header().Get("X-Content-Type-Options"); got != "nosniff" {
				t.Fatalf("X-Content-Type-Options = %q, want nosniff", got)
			}
			// THE POINT: what the browser receives must be a well-formed XML
			// document. A drain to EOF with encoding/xml is the same parse the
			// browser's XML parser performs (and the same one the card names).
			if err := drainServedXML(rec.Body.Bytes()); err != nil {
				t.Fatalf("served body is not a well-formed XML document: %v", err)
			}
		})
	}
}

// drainServedXML parses a served SVG body to EOF with encoding/xml.
func drainServedXML(body []byte) error {
	dec := xml.NewDecoder(bytes.NewReader(body))
	for {
		if _, err := dec.Token(); err != nil {
			if err == io.EOF {
				return nil
			}
			return err
		}
	}
}
