package mcpsrv

// t_20af3915: the MCP upload path is the dashboard's sibling, not a separate
// product — upload_media kind=asset stores merchant bytes that /media then
// serves as `image/svg+xml`. A body that is not a well-formed XML document has
// text before its root element, which is a fatal XML parse error in the
// browser, so it must be refused HERE too: a rule enforced only on the REST edge
// would let an agent store exactly the asset the dashboard refuses.
//
// The same two halves as the REST test: the prod-measured banner body is
// rejected, the XML-legal comment control is stored as `.svg` / image/svg+xml.
//
// Integration test: needs real Postgres (JOMFORM_TEST_DATABASE_URL), skipped
// when unset. Uses the in-memory bucket from media_upload_size_parity_test.go.

import (
	"context"
	"encoding/base64"
	"os"
	"strings"
	"testing"

	"github.com/wzul/jomform/api/internal/dbstore"
	"github.com/wzul/jomform/api/internal/objstore"
	"github.com/wzul/jomform/api/internal/testdb"
)

// mcpBannerSVG is the exact body measured on prod v1.21.233 (card t_20af3915).
const mcpBannerSVG = "/* Acme logo banner */\n" +
	`<svg xmlns="http://www.w3.org/2000/svg" width="10" height="10"><rect width="10" height="10"/></svg>` + "\n"

// mcpCommentSVG is the XML-legal control from the same measurement.
const mcpCommentSVG = "<!-- generated by Acme -->\n" +
	`<svg xmlns="http://www.w3.org/2000/svg" width="10" height="10"><rect width="10" height="10"/></svg>` + "\n"

func TestUploadMediaAssetRefusesNonWellFormedSVG(t *testing.T) {
	if strings.TrimSpace(os.Getenv("JOMFORM_TEST_DATABASE_URL")) == "" {
		t.Skip("JOMFORM_TEST_DATABASE_URL not set; skipping upload_media SVG well-formedness test")
	}
	ctx := context.Background()
	pool := testdb.Open(t)

	var userID string
	if err := pool.QueryRow(ctx,
		`INSERT INTO users (email, password_hash)
		 VALUES ('svgx-' || md5(random()::text) || '@example.test', 'it') RETURNING id`).Scan(&userID); err != nil {
		t.Fatalf("create user: %v", err)
	}
	var accountID string
	if err := pool.QueryRow(ctx,
		`INSERT INTO accounts (owner_user_id, name, slug)
		 SELECT $1, 'svgx-acc-' || md5(random()::text), 'svgx-' || md5(random()::text)
		 RETURNING id`, userID).Scan(&accountID); err != nil {
		t.Fatalf("create account: %v", err)
	}

	store, fake := newFakeStore(t)
	media := dbstore.NewMediaStore(pool)
	srv := &Server{deps: &Deps{Media: media, Store: store}}
	callCtx := WithAuthIdentity(ctx, &AuthIdentity{
		AccountID: accountID,
		Scopes:    []string{dbstore.ScopeReadWrite},
	})

	// Refused: the banner body never reaches the store.
	_, _, err := srv.uploadMedia(callCtx, nil, uploadMediaIn{
		Kind: "asset", Data: base64.StdEncoding.EncodeToString([]byte(mcpBannerSVG)),
	})
	if err == nil {
		t.Fatal("upload_media kind=asset stored a banner-led SVG; the browser shows a parsererror for it")
	}
	if !strings.Contains(err.Error(), "not valid XML") {
		t.Fatalf("upload_media error = %q, want it to name the XML well-formedness problem", err)
	}
	var svgRows int
	if qerr := pool.QueryRow(ctx,
		`SELECT count(*) FROM media WHERE account_id = $1 AND "key" LIKE '%.svg'`, accountID).Scan(&svgRows); qerr != nil {
		t.Fatalf("count media rows: %v", qerr)
	}
	if svgRows != 0 {
		t.Fatalf("%d .svg media row(s) stored for the refused body, want 0", svgRows)
	}

	// Accepted: an XML-legal document still uploads and is labelled SVG.
	_, out, err := srv.uploadMedia(callCtx, nil, uploadMediaIn{
		Kind: "asset", Data: base64.StdEncoding.EncodeToString([]byte(mcpCommentSVG)),
	})
	if err != nil {
		t.Fatalf("upload_media kind=asset rejected the XML-legal control: %v", err)
	}
	if !strings.HasSuffix(out.Key, ".svg") {
		t.Fatalf("control stored under %q, want a .svg key", out.Key)
	}
	if out.Mime != "image/svg+xml" {
		t.Fatalf("control media.mime = %q, want image/svg+xml", out.Mime)
	}
	if _, ok := fake.size(out.Key); !ok {
		t.Fatalf("control bytes missing from the store at %q", out.Key)
	}
	// And the bytes on the object are the ones that were validated, not a
	// re-encoded copy (SVG is stored as-is). The stored content-type is already
	// asserted through the media row above: objstore.GetObject derives its
	// answer by sniffing when the store returns a generic type, which the
	// in-memory bucket always does, so the row is the authority here.
	stored, _, err := store.GetObject(ctx, out.Key)
	if err != nil {
		t.Fatalf("GetObject(%q): %v", out.Key, err)
	}
	if string(stored) != mcpCommentSVG {
		t.Fatalf("stored object = %d bytes, want the %d uploaded bytes verbatim", len(stored), len(mcpCommentSVG))
	}
	if err := objstore.ValidateXMLDocument(stored); err != nil {
		t.Fatalf("stored control is not well-formed XML: %v", err)
	}
}
